"""Generate shared assets. Run with --check in CI; outputs are committed."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADER = '// Generated by tool/generate_shared.py; edit the source assets/templates.\n'


def outputs(root=ROOT):
    catalog = json.loads((root / 'assets/catalog/websites.json').read_text())
    tokens = json.loads((root / 'assets/design/design_tokens.json').read_text())
    result = {}
    def put(path, text):
        result[path] = text.encode('utf-8')
    colors, sizes = tokens['colors'], tokens['sizes']
    for value in colors.values():
        if not re.fullmatch(r'#[0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?', value):
            raise ValueError('Invalid color token')
    dart = "import 'package:flutter/material.dart';\n\nclass Palette {\n"
    dart += ''.join(f"  static const {key} = Color(0x{value[1:] if len(value) == 9 else 'FF' + value[1:]});\n" for key, value in colors.items())
    dart += '}\n\nclass Design {\n' + f"  static const fontFamily = {repr(tokens['fontFamily'])};\n"
    dart += ''.join(f'  static const {key} = {value if key.endswith("Ms") else float(value)};\n' for key, value in sizes.items()) + '}\n'
    put('lib/src/theme/design_tokens.dart', HEADER + dart)
    css = '/* Generated by tool/generate_shared.py. */\n:root {\n'
    for key, value in colors.items():
        # JSON/Dart use ARGB, CSS uses RGBA.
        if len(value) == 9:
            value = '#' + value[3:] + value[1:3]
        css += f'  --{key}: {value};\n'
    css += f"  --font-family: {repr(tokens['fontFamily'])};\n"
    css += ''.join(f"  --{key}: {value}{'ms' if key.endswith('Ms') else 'px'};\n" for key, value in sizes.items()) + '}\n'
    for font in tokens['fonts']:
        filename = font['file']
        if Path(filename).name != filename:
            raise ValueError('Font must be a filename')
        css += f'''@font-face {{
  font-family: {json.dumps(tokens['fontFamily'])};
  src: url("../assets/fonts/{filename}") format("truetype");
  font-style: normal;
  font-weight: {font['weight']};
  font-display: swap;
}}
'''
        result[f'extension/assets/fonts/{filename}'] = (root / 'assets/fonts' / filename).read_bytes()
    for license_file in (root / 'assets/fonts').glob('OFL-*.txt'):
        result['extension/assets/fonts/' + license_file.name] = license_file.read_bytes()
    put('extension/popup/shared.css', css)
    sites = [{key: site[key] for key in ('name', 'url', 'mark')} for site in catalog['sites']]
    put('extension/popup/sites.js', HEADER + 'const websites = ' + json.dumps(sites, indent=2, ensure_ascii=False) + ';\n')
    manifest = json.loads((root / 'extension/manifest.json').read_text())
    scripts = []
    for site in catalog['sites']:
        selectors = []
        for rule in site['rules']:
            if rule.get('enabled', True) and site.get('enabled', True):
                # shortcut: static CSS supports site-wide hide rules; extend generation for scoped actions.
                if set(rule['hosts']) != set(site['hosts']) or rule.get('parentHosts'):
                    raise ValueError('Static extension CSS requires rule hosts to match site hosts')
                for action in rule['actions']:
                    if action['type'] != 'hide':
                        raise ValueError('Site extension rules currently support hide only')
                    selectors.extend(action['selectors'])
        filename = f"rules/{site['id']}.css"
        put('extension/' + filename, '/* Generated from assets/catalog/websites.json. */\n' + ',\n'.join(selectors) + (' {\n  display: none !important;\n}\n' if selectors else ''))
        script = {'matches': [f'{scheme}://{host}/*' for host in site['hosts'] for scheme in ('https', 'http')], 'css': [filename], 'run_at': 'document_start', 'all_frames': True}
        if site['id'] == 'animeruka':
            script['js'] = ['content/animeruka-hide-ads.js']
        scripts.append(script)
    globals_ = catalog.get('globalRules', [])
    if (len(globals_) != 1 or globals_[0]['hosts'] != ['*']
            or globals_[0].get('parentHosts') or not globals_[0]['actions']
            or any(action['type'] != 'tapWhenVisible' for action in globals_[0]['actions'])):
        raise ValueError('Expected the global skip-button rule')
    selectors = [s for action in globals_[0]['actions'] for s in action['selectors']]
    if globals_[0].get('enabled', True):
        scripts.append({'matches': ['https://*/*', 'http://*/*'], 'js': ['content/adgate-skip-global.js'], 'run_at': 'document_start', 'all_frames': True})
    manifest['content_scripts'] = scripts
    put('extension/manifest.json', json.dumps(manifest, indent=2) + '\n')
    visibility = (root / 'tool/templates/runtime/visibility.js').read_text()
    for template, destination in [('rule_runtime.js.in', 'assets/runtime/rule_runtime.js'), ('adgate-skip-global.js.in', 'extension/content/adgate-skip-global.js')]:
        text = (root / 'tool/templates/runtime' / template).read_text().replace('__VISIBILITY__', visibility)
        if template.startswith('adgate'):
            text = text.replace('__SKIP_SELECTOR__', json.dumps(','.join(selectors)))
        put(destination, HEADER + text)
    animeruka_selectors = [
        selector
        for site in catalog['sites'] if site['id'] == 'animeruka'
        for rule in site['rules'] if rule.get('enabled', True) and site.get('enabled', True)
        for action in rule['actions'] if action['type'] == 'hide'
        for selector in action['selectors']
    ]
    animeruka_runtime = (root / 'tool/templates/runtime/animeruka-hide-ads.js.in').read_text()
    put('extension/content/animeruka-hide-ads.js', HEADER + animeruka_runtime.replace('__HIDE_SELECTORS__', json.dumps(animeruka_selectors)))
    pubspec = (root / 'pubspec.yaml').read_text()
    font_block = '  fonts:\n    # Generated from assets/design/design_tokens.json.\n    - family: ' + tokens['fontFamily'] + '\n      fonts:\n'
    for font in tokens['fonts']:
        font_block += '        - asset: assets/fonts/' + font['file'] + '\n'
        if font['weight'] != 400:
            font_block += f"          weight: {font['weight']}\n"
    pubspec = re.sub(r'  fonts:\n.*?(?=\nflutter_launcher_icons:)', font_block, pubspec, flags=re.S)
    pubspec = re.sub(r'adaptive_icon_background: .*', 'adaptive_icon_background: "' + colors['panel'] + '" # Generated from assets/design/design_tokens.json.', pubspec)
    put('pubspec.yaml', pubspec)
    put('android/app/src/main/res/values/colors.xml', '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_shared.py. -->\n<resources>\n    <color name="ic_launcher_background">' + colors['panel'] + '</color>\n</resources>\n')
    return result


def generate(root=ROOT, check=False):
    stale = []
    for name, data in outputs(root).items():
        path = root / name
        if not path.is_file() or path.read_bytes() != data:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if check and stale:
        raise ValueError('Generated files need updating: ' + ', '.join(stale))
    return stale


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        changed = generate(check=args.check)
    except ValueError as error:
        parser.exit(1, str(error) + '\n')
    print('Shared assets checked' if args.check else f'Updated {len(changed)} shared files')
